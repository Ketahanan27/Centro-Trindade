import fs from 'node:fs';
import path from 'node:path';
import dotenv from 'dotenv';
import pg from 'pg';

dotenv.config({ quiet: true });
const source = fs.readFileSync(path.resolve('erp-centro-trindade.sql'), 'utf8');
const quote = (name) => `"${name}"`;
const tables = [];
const deferred = [];
const statements = [];

// Parse MySQL string escapes without printing personal data from the dump.
function valuesToPostgres(input) {
  let output = '';
  let count = 0;
  let depth = 0;
  for (let i = 0; i < input.length; i++) {
    const char = input[i];
    if (char === "'") {
      let value = '';
      let closed = false;
      while (++i < input.length) {
        if (input[i] === '\\') {
          const escaped = input[++i];
          const escapes = { '0': '\0', b: '\b', n: '\n', r: '\r', t: '\t', Z: '\x1a' };
          value += escapes[escaped] ?? escaped;
        } else if (input[i] === "'") {
          if (input[i + 1] === "'") { value += "'"; i++; }
          else { closed = true; break; }
        } else value += input[i];
      }
      if (!closed || value.includes('\0')) throw new Error('String inválida ou NUL no backup.');
      let tag = '$dump$';
      while (value.includes(tag)) tag = tag.slice(0, -1) + '_$';
      output += tag + value + tag;
    } else {
      if (!/[\s(),.0-9eE+\-NULL]/.test(char)) throw new Error('Formato de valores não suportado.');
      if (char === '(') { if (depth++ === 0) count++; }
      if (char === ')') depth--;
      output += char;
    }
  }
  if (depth !== 0) throw new Error('Parênteses desequilibrados no backup.');
  return { sql: output, count };
}

for (const match of source.matchAll(/CREATE TABLE `([^`]+)` \(([\s\S]*?)\) ENGINE=([^;]+);/g)) {
  const [, name, body, options] = match;
  const lines = [];
  const columns = [];
  for (let line of body.trim().split(/\r?\n/)) {
    line = line.trim().replace(/,$/, '');
    if (line.startsWith('CONSTRAINT ')) {
      deferred.push(`ALTER TABLE ${quote(name)} ADD ${line.replace(/`([^`]+)`/g, '"$1"')};`);
      continue;
    }
    const index = line.match(/^(UNIQUE )?KEY `([^`]+)` \((.+)\)$/);
    if (index) {
      deferred.push(`CREATE ${index[1] ?? ''}INDEX ${quote(name + '_' + index[2])} ON ${quote(name)} (${index[3].replace(/`([^`]+)`/g, '"$1"')});`);
      continue;
    }
    const column = line.match(/^`([^`]+)`/);
    if (column) columns.push(column[1]);
    line = line.replace(/`([^`]+)`/g, '"$1"');
    line = line.replace(/enum\(((?:'[^']*',?)+)\)/, (_, values) => `text CHECK (${quote(column[1])} IN (${values}))`);
    line = line.replace(/\bint\b/g, 'integer').replace(/tinyint\(1\)/g, 'smallint');
    line = line.replace(/\bdatetime\b/g, 'timestamp without time zone');
    line = line.replace(/AUTO_INCREMENT/g, 'GENERATED BY DEFAULT AS IDENTITY');
    lines.push(line);
  }
  tables.push({ name, columns, next: Number(options.match(/AUTO_INCREMENT=(\d+)/)?.[1] ?? 1), count: 0 });
  statements.push(`CREATE TABLE ${quote(name)} (\n  ${lines.join(',\n  ')}\n);`);
}
if (tables.length !== 9) throw new Error('Estrutura inesperada: são esperadas nove tabelas.');
for (const line of source.split(/\r?\n/)) {
  if (!line.startsWith('INSERT INTO ')) continue;
  const match = line.match(/^INSERT INTO `([^`]+)` VALUES ([\s\S]*);$/);
  if (!match) throw new Error('INSERT não suportado no backup.');
  const table = tables.find((item) => item.name === match[1]);
  if (!table) throw new Error('Tabela desconhecida no backup.');
  const values = valuesToPostgres(match[2]);
  table.count += values.count;
  statements.push(`INSERT INTO ${quote(table.name)} (${table.columns.map(quote).join(', ')}) VALUES ${values.sql};`);
}
statements.push(...deferred);
for (const table of tables) {
  statements.push(`SELECT setval(pg_get_serial_sequence('${table.name}', 'id'), GREATEST(COALESCE((SELECT MAX(id) + 1 FROM ${quote(table.name)}), 1), ${table.next}), false);`);
}
const sql = `-- Importar apenas numa base PostgreSQL vazia. Contém dados pessoais.\nBEGIN;\nSET LOCAL TIME ZONE 'UTC';\n${statements.join('\n\n')}\nCOMMIT;\n`;
fs.mkdirSync('migration', { recursive: true });
fs.writeFileSync('migration/erp-centro-trindade.postgresql.sql', sql, 'utf8');
console.log('Backup convertido. Registos esperados:', JSON.stringify(Object.fromEntries(tables.map((t) => [t.name, t.count]))));

if (process.argv.includes('--import')) {
  if (!process.env.DATABASE_URL) throw new Error('DATABASE_URL não configurada.');
  const client = new pg.Client({ connectionString: process.env.DATABASE_URL, connectionTimeoutMillis: 15000 });
  try {
    await client.connect();
    await client.query('BEGIN');
    await client.query("SET LOCAL TIME ZONE 'UTC'");
    const existing = await client.query("SELECT tablename FROM pg_tables WHERE schemaname = 'public'");
    if (existing.rowCount) throw new Error('A base de destino contém tabelas. Importação cancelada.');
    for (const statement of statements) await client.query(statement);
    for (const table of tables) {
      const result = await client.query(`SELECT COUNT(*)::integer AS count FROM ${quote(table.name)}`);
      if (result.rows[0].count !== table.count) throw new Error('Contagem de registos incorreta.');
    }
    await client.query('COMMIT');
    console.log('Importação concluída: todas as contagens e restrições verificadas.');
  } catch (error) {
    await client.query('ROLLBACK').catch(() => {});
    console.error('Importação cancelada e revertida:', error.code ?? 'erro', String(error.message).replace(/postgres(?:ql)?:\/\/\S+/g, '[ligação omitida]'));
    process.exitCode = 1;
  } finally { await client.end(); }
}
